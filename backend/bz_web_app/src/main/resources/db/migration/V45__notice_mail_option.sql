-- ============================================
-- BareZen_Base V45: 公告发布可选邮件渠道
-- ============================================
-- 背景：邮件是可选的通知发送方式之一（工资发放、放假通知等场景需要邮箱留痕），
--       大部分通知默认站内推送（WebSocket 在线 + 公告列表展示）。
--       本迁移为 sys_notice 增加 send_email 标记：发布公告时可选择是否同步发送邮件。
-- 说明：仅新增列，不修改历史数据；默认 N（不发送），与"站内推送为主、邮件可选"一致。

ALTER TABLE `sys_notice`
  ADD COLUMN `send_email` char(1) DEFAULT 'N' COMMENT '发布时是否同步发送邮件（Y=是 N=否，默认 N）' AFTER `require_read`;