--
-- 背景：前端 format.ts 与菜单管理页均以 status='0' 表示"正常"、'1' 表示"停用"
-- （与 RuoYi 惯例一致），但早期种子脚本 V3/V6/V29 等将启用菜单写成了 status='1'，
-- V47 薪资菜单又写成 '0'，导致菜单管理页展示状态互相矛盾。
-- 后端菜单树与权限链路均不过滤 status，本归一化对功能零影响，仅修正展示语义。
--
-- 说明：不动历史迁移脚本（Flyway 校验和不可破坏），仅以本脚本做数据修正。

